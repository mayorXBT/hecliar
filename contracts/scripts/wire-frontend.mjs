import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { isAddress } from "viem";

const __dirname = dirname(fileURLToPath(import.meta.url));
const deploymentPath = resolve(__dirname, "..", "ignition", "deployments", "chain-84532", "deployed_addresses.json");
const envPath = resolve(__dirname, "..", "..", "frontend", ".env.deployed");

let deployment;
try {
  deployment = JSON.parse(readFileSync(deploymentPath, "utf8"));
} catch {
  console.error("Missing deployment output at", deploymentPath);
  console.error("Run: npm --workspace contracts run deploy:testnet");
  process.exit(1);
}

// Ignition keys entries as "<ModuleName>#<ContractName>", so the module can be
// renamed without this script silently finding nothing. Match on the contract
// half rather than hardcoding the module name.
const entry = Object.entries(deployment).find(([key]) => key.endsWith("#HecliarGame"));
const address = entry?.[1];
if (!address || !isAddress(address)) {
  console.error("Deployment file does not contain a valid HecliarGame address.");
  console.error("Keys present:", Object.keys(deployment).join(", ") || "(none)");
  process.exit(1);
}

const envContent = [
  "# Generated by contracts/scripts/wire-frontend.mjs",
  `NEXT_PUBLIC_HECLIAR_ADDRESS=${address}`,
  "NEXT_PUBLIC_NETWORK=testnet",
  "NEXT_PUBLIC_CHAIN_ID=84532",
  "",
].join("\n");

writeFileSync(envPath, envContent, "utf8");
console.log("Frontend wired to HecliarGame at", address);
console.log("Source:", envPath);
console.log("Load with: cp frontend/.env.deployed frontend/.env.local");
